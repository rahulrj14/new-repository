String nicknameFor(int id) {
  final a = (id ~/ animals.length) % adjectives.length;
  final b = id % animals.length;
  return '${adjectives[a]} ${animals[b]}';
}

int randomNicknameId([Random? rng]) =>
    (rng ?? Random()).nextInt(adjectives.length * animals.length);
